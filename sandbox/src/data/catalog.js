// Declares exactly what this sandbox implements, for the OGC-style discovery endpoints
// (/collections, /processes). Keep in sync with README.md's "What's implemented" table.
//
// Each process's `inputs`/`outputs` describes the fields of its `{ "inputs": {...} }` request
// body / response body, as OGC API - Processes' inputDescription/outputDescription (TOMP-API.yaml
// schemas `process`, `inputDescription`, `outputDescription`). `schema` is a $ref into the
// OpenAPI document served at GET /api, rather than a duplicated inline copy, so it can't drift
// out of sync with TOMP-API.yaml.

function ref(schemaName) {
  return { $ref: `/api#/components/schemas/${schemaName}` };
}

function input(title, schemaName, { description, minOccurs = 1, maxOccurs = 1 } = {}) {
  return { title, description, schema: ref(schemaName), minOccurs, maxOccurs };
}

function output(title, schemaName, description) {
  return { title, description, schema: ref(schemaName) };
}

